
#14. The length of one of the diagonals of a field in the form 
# of a quadrilateral is 46 m. The perpendicular distance 
# of the other two vertices from the diagonal are 13 m 
# and 10 m, find the area of the field.

diagonal=46
side=13
side2=10

diagonal2=(side+side2)
area_of_field=(diagonal*diagonal2)/2
print(f"area of field:{area_of_field}")