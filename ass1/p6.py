side_1=10
side_2=9
parameter=36

side_3=parameter-(side_1+side_2)

semi_parameter=parameter//2

area=semi_parameter*(semi_parameter-side_1)*(semi_parameter-side_2)*(semi_parameter-side_3)

print(area**0.5) #In Python, the ** operator is used for exponentiation (raising a number to a power).Mathematically, taking the square root of a number is the exact same as raising that number to the power of $\frac{1}{2}$ (or 0.5).